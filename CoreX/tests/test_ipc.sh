#!/bin/bash
# ============================================================================
# test_ipc.sh — CoreX 无锁队列 IPC 性能与正确性验证套件
# ============================================================================
# 用法:
#   ./test_ipc.sh [命令]
#
# 命令:
#   build               编译 test_ipc 测试程序
#   run                 编译并运行全部测试
#   run-pingpong        仅运行场景1 (Ping-Pong 极限延迟)
#   run-throughput      仅运行场景2 (大数据流吞吐)
#   clean               清理编译产物
#   help                显示此帮助信息
#
# 示例:
#   ./test_ipc.sh build && ./test_ipc.sh run
#   ./test_ipc.sh run-pingpong
#   ./test_ipc.sh run-throughput
# ============================================================================
set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
BUILD_DIR="$PROJECT_DIR/build"
BINARY="$BUILD_DIR/test_ipc"

# 颜色定义
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
BOLD='\033[1m'
NC='\033[0m' # No Color

# ============================================================================
# 帮助与说明
# ============================================================================

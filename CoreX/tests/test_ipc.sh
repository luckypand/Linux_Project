# ============================================================================
# 构建
# ============================================================================
do_build() {
    echo -e "${BOLD}[构建] 编译 test_ipc...${NC}"
    cd "$PROJECT_DIR"
    ./build.sh test_ipc
    echo -e "${GREEN}[构建] 完成${NC}"
}

# ============================================================================
# 运行
# ============================================================================
do_run_all() {
    echo ""
    echo -e "${BOLD}${CYAN}═══════════════════════════════════════════════════${NC}"
    echo -e "${BOLD}${CYAN}  运行全部测试场景${NC}"
    echo -e "${BOLD}${CYAN}═══════════════════════════════════════════════════${NC}"

    if [ ! -x "$BINARY" ]; then
        echo -e "${YELLOW}[提示] 可执行文件不存在，先执行编译...${NC}"
        do_build
    fi

    show_timing_diagram
    show_architecture_diagram

    echo ""
    echo -e "${BOLD}${GREEN}[执行] 开始运行 test_ipc --mode all${NC}"
    echo ""

    "$BINARY" --mode all

    local ret=$?
    echo ""
    if [ $ret -eq 0 ]; then
        echo -e "${GREEN}${BOLD}✅ 全部测试通过！${NC}"
    else
        echo -e "${RED}${BOLD}❌ 部分测试失败，退出码: $ret${NC}"
    fi
    return $ret
}

do_run_pingpong() {
    echo ""
    echo -e "${BOLD}${CYAN}场景1: Ping-Pong 极限延迟测试${NC}"
    echo ""

    if [ ! -x "$BINARY" ]; then
        echo -e "${YELLOW}[提示] 可执行文件不存在，先执行编译...${NC}"
        do_build
    fi

    show_timing_diagram

    echo ""
    "$BINARY" --mode pingpong
    return $?
}

do_run_throughput() {
    echo ""
    echo -e "${BOLD}${CYAN}场景2: 车载大数据流吞吐测试${NC}"
    echo ""

    if [ ! -x "$BINARY" ]; then
        echo -e "${YELLOW}[提示] 可执行文件不存在，先执行编译...${NC}"
        do_build
    fi

    show_architecture_diagram

    echo ""
    "$BINARY" --mode throughput
    return $?
}

do_clean() {
    echo -e "${BOLD}[清理] 删除构建产物...${NC}"
    rm -f "$BINARY"
    echo -e "${GREEN}[清理] 完成${NC}"
}

# ============================================================================
# 主命令分发
# ============================================================================
case "${1:-help}" in
    build)
        do_build
        ;;
    run)
        do_run_all
        ;;
    run-pingpong)
        do_run_pingpong
        ;;
    run-throughput)
        do_run_throughput
        ;;
    clean)
        do_clean
        ;;
    help|--help|-h)
        show_help
        echo ""
        show_timing_diagram
        echo ""
        show_architecture_diagram
        echo ""
        echo -e "${BOLD}可用命令:${NC}"
        echo "  build               编译测试程序"
        echo "  run                 编译并运行全部测试（含时序图/架构图）"
        echo "  run-pingpong        仅运行场景1 (Ping-Pong)"
        echo "  run-throughput      仅运行场景2 (大数据吞吐)"
        echo "  clean               清理编译产物"
        echo "  help                显示此帮助"
        echo ""
        echo -e "${BOLD}快速开始:${NC}"
        echo "  cd \$(dirname \$0)/.. && ./tests/test_ipc.sh build && ./tests/test_ipc.sh run"
        ;;
    *)
        echo -e "${RED}未知命令: $1${NC}"
        echo "请使用 'help' 查看可用命令"
        exit 1
        ;;
esac
